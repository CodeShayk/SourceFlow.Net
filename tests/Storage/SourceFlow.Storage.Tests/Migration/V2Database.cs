using System.Data.Common;
using System.Globalization;
using System.Text;
using Bank.Accounts;
using SourceFlow.Migration;

namespace SourceFlow.Storage.Tests.Migration;

/// <summary>
/// A seeded v2 database (plan 06 §6): the v2 EF <c>CommandRecord</c> DDL and entity tables, with rows replaying the v2 E2E
/// account scenario as SQL (no v2 code is referenced). One schema per test; the archive schema is per test too.
/// </summary>
public sealed class V2Database
{
    /// <summary>The v2 E2E command types, as v2 stored them (assembly-qualified, with version).</summary>
    public const string Commands = "SourceFlow.Core.Tests.E2E.Commands.";

    public const string Assembly = ", SourceFlow.Core.Tests, Version=1.0.0.0, Culture=neutral, PublicKeyToken=null";

    /// <summary>A command type v2 could not rebuild (GAP-04: no public parameterless constructor).</summary>
    public const string ApplyInterest = "Legacy.Banking.ApplyInterest, Legacy.Banking, Version=2.0.0.0, Culture=neutral, PublicKeyToken=null";

    /// <summary>A command of another v2 entity type that shares the command table (ids overlap per type).</summary>
    public const string PlaceOrder = "Shop.Commands.PlaceOrder, Shop, Version=1.0.0.0, Culture=neutral, PublicKeyToken=null";

    /// <summary>The generated accounts: ids 2000..2039.</summary>
    public const int Generated = 40;

    private V2Database(DbDataSource dataSource, V2Dialect dialect, string schema, string connectionString)
    {
        DataSource = dataSource;
        Dialect = dialect;
        Schema = schema;
        ConnectionString = connectionString;
        ArchiveSchema = schema + "_archive";
        Source = new V2Source(dataSource, dialect) { Schema = schema, ArchiveSchema = ArchiveSchema };
    }

    public DbDataSource DataSource { get; }

    public V2Dialect Dialect { get; }

    public string Schema { get; }

    public string ArchiveSchema { get; }

    public string ConnectionString { get; }

    public V2Source Source { get; }

    /// <summary>The <c>--v2-*</c> options of the global tool for this database.</summary>
    public string[] ToolOptions =>
    [
        "--v2-connection", ConnectionString, "--v2-provider", Dialect == V2Dialect.SqlServer ? "sqlserver" : "postgresql",
        "--v2-schema", Schema, "--v2-archive-schema", ArchiveSchema,
    ];

    /// <summary>Every v2 account: id, name, balance, closed.</summary>
    public static IReadOnlyList<(int Id, string Name, decimal Balance, bool Closed)> Accounts { get; } =
    [
        (999, "John Doe", 1400m, true),
        (1000, "Jane Roe", 250m, false),
        (1001, "Ada Lovelace", 520.5m, false),
        .. Enumerable.Range(0, Generated).Select(i => (2000 + i, "Customer " + i.ToString(CultureInfo.InvariantCulture), 10m * (i + 1), i % 7 == 0)),
    ];

    public static async Task<V2Database> CreateAsync(DbDataSource dataSource, V2Dialect dialect, string schema, string connectionString)
    {
        var database = new V2Database(dataSource, dialect, schema, connectionString);
        await database.ExecuteAsync(database.Ddl());
        await database.ExecuteAsync(database.Seed());
        return database;
    }

    public string Q(string identifier)
    {
        return Dialect == V2Dialect.SqlServer ? "[" + identifier + "]" : "\"" + identifier + "\"";
    }

    public string T(string table)
    {
        return Q(Schema) + "." + Q(table);
    }

    public async Task ExecuteAsync(string sql)
    {
        await using DbConnection connection = await DataSource.OpenConnectionAsync(TestContext.Current.CancellationToken);
        await using DbCommand command = connection.CreateCommand();
        command.CommandText = sql;
        await command.ExecuteNonQueryAsync(TestContext.Current.CancellationToken);
    }

    public async Task<long> ScalarAsync(string sql)
    {
        await using DbConnection connection = await DataSource.OpenConnectionAsync(TestContext.Current.CancellationToken);
        await using DbCommand command = connection.CreateCommand();
        command.CommandText = sql;
        return Convert.ToInt64(await command.ExecuteScalarAsync(TestContext.Current.CancellationToken), CultureInfo.InvariantCulture);
    }

    // The v2 EF model: CommandRecordConfiguration (unique EntityId+SequenceNo, indexes on EntityId and Timestamp) and the
    // entity table EF creates for the v2 E2E BankAccount; plus a v2 view-model table, which holds no entities.
    private string Ddl()
    {
        bool sql = Dialect == V2Dialect.SqlServer;
        string text = sql ? "nvarchar(max)" : "text";
        string name = sql ? "nvarchar(500)" : "varchar(500)";
        string time = sql ? "datetime2" : "timestamp";
        string identity = sql ? "bigint IDENTITY(1,1)" : "bigint GENERATED BY DEFAULT AS IDENTITY";
        string boolean = sql ? "bit" : "boolean";
        string createSchema = sql ? $"EXEC(N'CREATE SCHEMA {Q(Schema)}');" : $"CREATE SCHEMA {Q(Schema)};";
        return $"""
            {createSchema}
            CREATE TABLE {T("CommandRecord")} (
              {Q("Id")} {identity} NOT NULL PRIMARY KEY,
              {Q("EntityId")} int NOT NULL,
              {Q("SequenceNo")} int NOT NULL,
              {Q("CommandName")} {name} NOT NULL,
              {Q("CommandType")} {name} NOT NULL,
              {Q("PayloadType")} {name} NOT NULL,
              {Q("PayloadData")} {text} NOT NULL,
              {Q("Metadata")} {text} NOT NULL,
              {Q("Timestamp")} {time} NOT NULL,
              {Q("CreatedAt")} {time} NOT NULL,
              {Q("UpdatedAt")} {time} NOT NULL);
            CREATE UNIQUE INDEX {Q("IX_CommandRecord_EntityId_SequenceNo")} ON {T("CommandRecord")} ({Q("EntityId")}, {Q("SequenceNo")});
            CREATE INDEX {Q("IX_CommandRecord_EntityId")} ON {T("CommandRecord")} ({Q("EntityId")});
            CREATE INDEX {Q("IX_CommandRecord_Timestamp")} ON {T("CommandRecord")} ({Q("Timestamp")});
            CREATE TABLE {T("BankAccount")} (
              {Q("Id")} int NOT NULL PRIMARY KEY,
              {Q("CreatedOn")} {time} NOT NULL,
              {Q("AccountName")} {text} NULL,
              {Q("Balance")} decimal(18,2) NOT NULL,
              {Q("IsClosed")} {boolean} NOT NULL,
              {Q("ClosureReason")} {text} NULL,
              {Q("ActiveOn")} {time} NOT NULL);
            CREATE TABLE {T("AccountViewModel")} (
              {Q("Id")} int NOT NULL PRIMARY KEY,
              {Q("AccountName")} {text} NULL,
              {Q("CurrentBalance")} decimal(18,2) NOT NULL,
              {Q("TransactionCount")} int NOT NULL);
            """;
    }

    private string Seed()
    {
        var sql = new StringBuilder();
        string True = Dialect == V2Dialect.SqlServer ? "1" : "true";
        string False = Dialect == V2Dialect.SqlServer ? "0" : "false";
        foreach ((int id, string name, decimal balance, bool closed) in Accounts)
        {
            string reason = closed ? "'Customer account close request'" : "''";
            sql.AppendLine(CultureInfo.InvariantCulture, $"INSERT INTO {T("BankAccount")} VALUES ({id}, '2025-01-10T09:00:00', '{name}', {balance.ToString(CultureInfo.InvariantCulture)}, {(closed ? True : False)}, {reason}, '2025-01-11T09:00:00');");
            sql.AppendLine(CultureInfo.InvariantCulture, $"INSERT INTO {T("AccountViewModel")} VALUES ({id}, '{name}', {balance.ToString(CultureInfo.InvariantCulture)}, 1);");
        }

        // Account 999 (the v2 E2E scenario, caller-assigned id): create, activate, deposit 500, withdraw 200, deposit 100, close.
        Command(sql, 999, 1, "CreateAccount", "Payload", "{\"id\":999,\"initialAmount\":1000,\"accountName\":\"John Doe\"}");
        Command(sql, 999, 2, "ActivateAccount", "ActivationPayload", "{\"id\":999,\"activeOn\":\"2025-01-11T09:00:00Z\"}");
        Command(sql, 999, 3, "DepositMoney", "TransactPayload", "{\"id\":999,\"type\":1,\"amount\":500}");
        Command(sql, 999, 4, "WithdrawMoney", "TransactPayload", "{\"id\":999,\"type\":2,\"amount\":200}");
        Command(sql, 999, 5, "DepositMoney", "TransactPayload", "{\"id\":999,\"type\":1,\"amount\":100}");
        Command(sql, 999, 6, "CloseAccount", "ClosurePayload", "{\"id\":999,\"isClosed\":true,\"closureReason\":\"Customer account close request\"}");

        // Another entity type shares the table and numbering (v2 sequences per entity id): not an account command.
        Command(sql, 999, 7, "PlaceOrder", "OrderPayload", "{\"id\":999}", PlaceOrder);

        // GAP-20: two accounts created without a caller-assigned id are logged under entity id 0.
        Command(sql, 0, 1, "CreateAccount", "Payload", "{\"id\":0,\"initialAmount\":200,\"accountName\":\"Jane Roe\"}");
        Command(sql, 0, 2, "CreateAccount", "Payload", "{\"id\":0,\"initialAmount\":500,\"accountName\":\"Ada Lovelace\"}");
        Command(sql, 1000, 1, "ActivateAccount", "ActivationPayload", "{\"id\":1000}");
        Command(sql, 1000, 2, "DepositMoney", "TransactPayload", "{\"id\":1000,\"type\":1,\"amount\":50}");

        // GAP-04: a command type v2 couldn't rebuild, and a row with an empty payload.
        Command(sql, 1001, 1, "ActivateAccount", "ActivationPayload", "{\"id\":1001}");
        Command(sql, 1001, 2, "ApplyInterest", "InterestPayload", "{\"rate\":0.041}", ApplyInterest);
        Command(sql, 1001, 3, "DepositMoney", "TransactPayload", string.Empty);

        for (int i = 0; i < Generated; i++)
        {
            Command(sql, 2000 + i, 1, "CreateAccount", "Payload", "{\"id\":" + (2000 + i).ToString(CultureInfo.InvariantCulture) + "}");
        }

        return sql.ToString();
    }

    /// <summary>The v2 commands: 7 for account 999 (one of them an order), 2 under id 0, 2 for 1000, 3 for 1001, 1 per generated account.</summary>
    public static int CommandCount => 7 + 2 + 2 + 3 + Generated;

    private void Command(StringBuilder sql, int entityId, int sequence, string name, string payload, string data, string? type = null)
    {
        type ??= Commands + name + Assembly;
        string payloadType = Commands + payload + Assembly;
        string columns = string.Join(", ", new[] { "EntityId", "SequenceNo", "CommandName", "CommandType", "PayloadType", "PayloadData", "Metadata", "Timestamp", "CreatedAt", "UpdatedAt" }.Select(Q));
        string time = "'2025-01-1" + Math.Min(sequence, 9).ToString(CultureInfo.InvariantCulture) + "T10:00:00'";
        sql.AppendLine(CultureInfo.InvariantCulture,
            $"INSERT INTO {T("CommandRecord")} ({columns}) VALUES ({entityId}, {sequence}, '{name}', '{type}', '{payloadType}', '{data}', '{{\"sequenceNo\":{sequence}}}', {time}, {time}, {time});");
    }
}

/// <summary>A row of the v2 <c>BankAccount</c> table, as <c>migrate v2 scaffold</c> generates it.</summary>
public sealed record V2BankAccount(int Id, DateTime CreatedOn, string? AccountName, decimal Balance, bool IsClosed, string? ClosureReason, DateTime ActiveOn) : IV2Entity<V2BankAccount>
{
    public static string TableName => "BankAccount";

    public static V2BankAccount Read(V2Row row)
    {
        return new(
            row.Int32("Id"),
            row.DateTime("CreatedOn"),
            row.String("AccountName"),
            row.Decimal("Balance"),
            row.Boolean("IsClosed"),
            row.String("ClosureReason"),
            row.DateTime("ActiveOn"));
    }
}

/// <summary>
/// Imports v2 accounts into the Bank sample's aggregate: the current state as <see cref="AccountOpened"/> (the balance
/// as the opening amount) and, for closed accounts, <see cref="AccountClosed"/>.
/// </summary>
public sealed class BankAccountImport : IV2Import<V2BankAccount, BankAccount, AccountId>
{
    /// <summary>Simulates an interruption: the import fails on this v2 id.</summary>
    public int? FailOn { get; set; }

    public AccountId MapId(V2BankAccount entity)
    {
        return V2Ids.FromLegacy<AccountId>(entity.Id);
    }

    public IEnumerable<IEvent> ToEvents(V2BankAccount entity, V2ImportContext context)
    {
        if (entity.Id == FailOn)
        {
            throw new InvalidOperationException($"Interrupted at v2 account {entity.Id}.");
        }

        AccountId id = MapId(entity);
        yield return new AccountOpened(id, entity.AccountName ?? string.Empty, entity.Balance, new DateTimeOffset(entity.CreatedOn, TimeSpan.Zero));
        if (entity.IsClosed)
        {
            yield return new AccountClosed(id, entity.ClosureReason ?? string.Empty, context.ImportedAt);
        }
    }

    public IEnumerable<string> Compare(V2BankAccount entity, BankAccount state)
    {
        if (state.Balance != entity.Balance)
        {
            yield return $"Balance: v2 {entity.Balance.ToString(CultureInfo.InvariantCulture)}, v3 {state.Balance.ToString(CultureInfo.InvariantCulture)}";
        }

        AccountStatus expected = entity.IsClosed ? AccountStatus.Closed : AccountStatus.Open;
        if (state.Status != expected)
        {
            yield return $"Status: v2 {expected}, v3 {state.Status}";
        }
    }

    public bool OwnsCommand(string commandType)
    {
        return !commandType.StartsWith("Shop.", StringComparison.Ordinal);
    }
}
