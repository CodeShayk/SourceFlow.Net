// Generates the performance fixtures (STU-PERF-01..02), deterministically:
//   node e2e/generate.mjs large-workflow <file>   a 200-state workflow (200 steps, with retries and compensations)
//   node e2e/generate.mjs large-workspace <dir>   a workspace of 20 services and 50 workflows
//   node e2e/generate.mjs editable-workspace <dir> a fresh copy of the commerce workspace for the editing, simulation
//                                                 and specs tests (STU-E2E-07..13): saves change these copies, never the
//                                                 committed files; orders has a test project for the specs
import { copyFileSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const [, , what, target] = process.argv;

function workflow(name, owner, steps, prefix) {
  const lines = [
    'sourceflow.workflow: 1',
    `name: ${name}`,
    'version: 1',
    `owner: ${owner}`,
    'start:',
    `  on: ${prefix}.started.v1`,
    '  correlate: data.id',
    'data:',
    '  id: { from: start.data.id }',
    'steps:',
  ];
  for (let i = 1; i <= steps; i++) {
    const id = `step-${String(i).padStart(3, '0')}`;
    lines.push(`  - id: ${id}`);
    lines.push(`    send: { command: ${prefix}.do-${i % 5}.v1, map: { id: $data.id } }`);
    lines.push('    await:');
    lines.push(`      success: ${prefix}.done-${i % 5}.v1`);
    if (i % 4 === 0) {
      lines.push('      failure:');
      lines.push(`        - rejected: ${prefix}.refused`);
      lines.push('          retry: { max: 2 }');
      lines.push('          then: fail');
    }

    if (i % 10 === 0) {
      lines.push('    timeout: { after: PT5M, then: manual }');
    }

    if (i % 6 === 0) {
      lines.push(`    compensate: { send: { command: ${prefix}.undo-${i % 5}.v1, map: { id: $data.id } }, await: { success: ${prefix}.undone-${i % 5}.v1 } }`);
    }
  }

  return lines.join('\n') + '\n';
}

function manifest(service, index, services) {
  const commands = [0, 1, 2, 3, 4].map((i) => ({ type: `${service}.do-${i}`, version: 1, emits: [`${service}.done-${i}.v1`], rejects: [`${service}.refused`] }));
  const next = services[(index + 1) % services.length];
  return {
    manifestVersion: 1,
    service,
    endpoint: service,
    sourceflowVersion: '3.0.0',
    messages: [],
    aggregates: [{ name: `${service}-root`, commands, events: commands.map((c) => c.emits[0]) }],
    processManagers: [],
    projections: [],
    publishes: [{ domainEvent: `${service}.done-0.v1`, as: `${service}.done-0.v1`, topic: `${service}.events` }],
    subscribes: [{ topic: `${next}.events` }],
    commandRoutes: [{ command: `${next}.do-0.v1`, to: next, replyOnReject: true }],
    workflows: [],
    schemas: [],
  };
}

if (what === 'large-workflow') {
  writeFileSync(target, '# Generated by e2e/generate.mjs (STU-PERF-01): 200 steps, retries, timeouts and compensations.\n' + workflow('large', 'orders', 200, 'orders'));
} else if (what === 'large-workspace') {
  const services = Array.from({ length: 20 }, (_, i) => `service-${String(i + 1).padStart(2, '0')}`);
  mkdirSync(join(target, 'manifests'), { recursive: true });
  const yaml = ['# Generated by e2e/generate.mjs (STU-PERF-02): 20 services, 50 workflows.', 'domain: large', 'description: A large generated domain', 'services:'];
  services.forEach((service, index) => {
    writeFileSync(join(target, 'manifests', `${service}.manifest.json`), JSON.stringify(manifest(service, index, services), null, 2) + '\n');
    yaml.push(`  - name: ${service}`, `    manifest: manifests/${service}.manifest.json`, `    workflows: ${service}/workflows`);
    const count = index < 10 ? 3 : 2; // 10 × 3 + 10 × 2 = 50
    mkdirSync(join(target, service, 'workflows'), { recursive: true });
    for (let w = 1; w <= count; w++) {
      writeFileSync(join(target, service, 'workflows', `flow-${w}.sfflow.yaml`), workflow(`${service}-flow-${w}`, service, 6, service));
    }
  });
  writeFileSync(join(target, 'sourceflow.domain.yaml'), yaml.join('\n') + '\n');
} else if (what === 'editable-workspace') {
  const golden = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', 'tests', 'workflow-golden');
  rmSync(target, { recursive: true, force: true });
  const workflows = join(target, 'orders', 'workflows');
  mkdirSync(workflows, { recursive: true });
  // Every golden case under its case name, and copies of order-fulfilment for the visual edits that are saved (E2E-09, and
  // keyboard-only A11Y-05), for the simulation and specs (E2E-11..13) and for the validation timing (PERF-03), so no test
  // reads a file another one is changing.
  for (const name of readdirSync(join(golden, 'cases'))) {
    copyFileSync(join(golden, 'cases', name, 'workflow.sfflow.yaml'), join(workflows, `${name}.sfflow.yaml`));
  }

  copyFileSync(join(golden, 'cases', '01-order-fulfilment', 'workflow.sfflow.yaml'), join(workflows, 'visual-edits.sfflow.yaml'));
  copyFileSync(join(golden, 'cases', '01-order-fulfilment', 'workflow.sfflow.yaml'), join(workflows, 'keyboard-edits.sfflow.yaml'));
  copyFileSync(join(golden, 'cases', '01-order-fulfilment', 'workflow.sfflow.yaml'), join(workflows, 'perf.sfflow.yaml'));
  copyFileSync(join(golden, 'cases', '01-order-fulfilment', 'workflow.sfflow.yaml'), join(workflows, 'simulation.sfflow.yaml'));
  mkdirSync(join(target, 'orders', 'tests'), { recursive: true });
  writeFileSync(join(target, 'orders', 'tests', 'Orders.Tests.csproj'), '<Project Sdk="Microsoft.NET.Sdk" />\n');

  const yaml = ['# Generated by e2e/generate.mjs (STU-E2E-07..13): the golden commerce domain, editable.', 'domain: commerce', 'description: Order to delivery', 'services:'];
  for (const service of ['orders', 'inventory', 'payments', 'shipping']) {
    yaml.push(`  - name: ${service}`, `    manifest: ${JSON.stringify(join(golden, 'domain', `${service}.manifest.json`))}`);
    if (service === 'orders') {
      yaml.push('    workflows: orders/workflows', '    tests: orders/tests', '    module: Orders.OrdersModule');
    }
  }

  writeFileSync(join(target, 'sourceflow.domain.yaml'), yaml.join('\n') + '\n');
} else {
  console.error('usage: node e2e/generate.mjs large-workflow <file> | large-workspace <dir> | editable-workspace <dir>');
  process.exit(2);
}
