    /// <summary>What the spec generator writes.</summary>
    public sealed class SpecOptions
    {
        /// <summary>The test namespace.</summary>
        public string Namespace { get; set; } = "Workflows.Tests";

        /// <summary>The generated workflow's type, for example <c>Orders.OrderFulfilmentWorkflowV1</c>; null uses the naming convention.</summary>
        public string? WorkflowType { get; set; }

        /// <summary>The owner's module type, for example <c>Orders.OrdersModule</c>.</summary>
        public string ModuleType { get; set; } = "Module";

        /// <summary>Every path instead of the minimal set that covers every edge.</summary>
        public bool AllPaths { get; set; }

        /// <summary>Only these path ids (for example the ones selected in the path explorer); overrides <see cref="AllPaths"/>.</summary>
        public IReadOnlyCollection<string>? PathIds { get; set; }
    }

    /// <summary>
    /// Generates <c>WorkflowSpec</c> tests (SourceFlow.Testing) for enumerated paths (doc 15 §6.1, WFD-34): per path, the
    /// start message, every outcome, the commands each transition sends, and the end status. Start data satisfies the
    /// path's guard decisions; event data carries the correlation key and distinct captured values.
    /// </summary>
    public static class SpecGenerator
    {
        /// <summary>The generated workflow type name: <c>OrderFulfilmentWorkflowV1</c>.</summary>
        public static string WorkflowTypeName(WorkflowDefinition workflow)
        {
            if (workflow is null)
            {
                throw new ArgumentNullException(nameof(workflow));
            }

            return Pascal(workflow.Name) + "WorkflowV" + workflow.Version.ToString(CultureInfo.InvariantCulture);
        }

        /// <summary>Generates the test class for <paramref name="workflow"/>.</summary>
        public static string Generate(WorkflowDefinition workflow, WorkflowEnvironment environment, SpecOptions? options = null, PathSet? paths = null)
        {
            if (workflow is null)
            {
                throw new ArgumentNullException(nameof(workflow));
            }

            if (environment is null)
            {
                throw new ArgumentNullException(nameof(environment));
            }

            options ??= new SpecOptions();
            paths ??= PathEnumerator.Enumerate(workflow);
            IEnumerable<WorkflowPath> selected = options.PathIds is { } ids
                ? paths.Paths.Where(p => ids.Contains(p.Id))
                : options.AllPaths ? paths.Paths : paths.MinimalCover();
            string type = options.WorkflowType ?? WorkflowTypeName(workflow);
            var text = new StringBuilder();
            text.Append("// <auto-generated>\n")
                .Append("// Generated by SourceFlow Studio from ").Append(workflow.ProcessName).Append(" (").Append(WorkflowFingerprint.Compute(workflow)).Append(").\n")
                .Append("// One test per path; regenerate after changing the workflow (edits are overwritten).\n")
                .Append("// </auto-generated>\n")
                .Append("#nullable enable\n")
                .Append("using SourceFlow.Testing;\n")
                .Append("using SourceFlow.Workflows;\n")
                .Append("using Xunit;\n\n")
                .Append("namespace ").Append(options.Namespace).Append(";\n\n")
                .Append("public sealed class ").Append(Pascal(workflow.Name)).Append("V").Append(workflow.Version).Append("PathTests\n{\n");

            bool first = true;
            foreach (WorkflowPath path in selected)
            {
                if (!first)
                {
                    text.Append('\n');
                }

                first = false;
                Test(text, workflow, environment, path, type, options.ModuleType);
            }

            return text.Append("}\n").ToString();
        }

        private static void Test(StringBuilder text, WorkflowDefinition workflow, WorkflowEnvironment environment, WorkflowPath path, string type, string module)
        {
            ManifestMessage? startMessage = environment.Message(workflow.Start.On);
            var samples = new Samples(workflow);
            Dictionary<string, object?> startData = samples.Message(startMessage, correlationValue: null);
            bool solved = SolveGuards(workflow, path, startData, startMessage);

            var options = new SimulationOptions { Guard = step => step == SimulationOptions.StartGuard || step.StartsWith(SimulationOptions.SuccessGuard, StringComparison.Ordinal) ? true : solved ? (bool?)null : path.Guards.TryGetValue(step, out bool run) ? run : (bool?)null };
            DateTimeOffset epoch = new DateTimeOffset(2026, 1, 1, 0, 0, 0, TimeSpan.Zero);
            SimulationResult result = WorkflowSimulator.Start(workflow, startData, epoch, options);
            string instance = result.State.Instance;

            text.Append("    /// <summary>").Append(Xml(path.ToString())).Append("</summary>\n");
            text.Append(solved ? "    [Fact]\n" : "    [Fact(Skip = \"No start data satisfies this path's guard decisions; supply it by hand.\")]\n");
            text.Append("    public void ").Append(path.Id).Append('_').Append(path.End).Append("()\n    {\n");
            text.Append("        var spec = WorkflowSpec.For<").Append(type).Append(", ").Append(module).Append(">();\n");
            text.Append("        spec.Start(\"").Append(workflow.Start.On).Append("\", ").Append(Json(startData)).Append(')');
            Sends(text, result);

            foreach (PathMove move in path.Moves.Where(m => m.Input is not null))
            {
                SimulationInput input = move.Input!;
                string call;
                switch (input)
                {
                    case SimulationInput.Outcome { Kind: "success" }:
                        string? eventType = Awaited(workflow, result.State);
                        ManifestMessage? message = eventType is null ? null : environment.Message(eventType);
                        Dictionary<string, object?> data = samples.Message(message, instance, Captures(workflow, result.State));
                        input = SimulationInput.Succeed(data);
                        call = "spec.Succeed(\"" + eventType + "\", " + Json(data) + ")";
                        break;
                    case SimulationInput.Outcome { Kind: "rejected" } rejected:
                        call = "spec.Reject(\"" + rejected.Value + "\")";
                        break;
                    case SimulationInput.Outcome failed:
                        Dictionary<string, object?> failure = samples.Message(environment.Message(failed.Value!), instance);
                        input = SimulationInput.FailWith(failed.Value!, failure);
                        call = "spec.Fail(\"" + failed.Value + "\", " + Json(failure) + ")";
                        break;
                    default:
                        call = "spec.FireTimer()";
                        break;
                }

                result = WorkflowSimulator.Step(result.State, input);
                text.Append("        ").Append(call);
                Sends(text, result);
            }

            text.Append("        spec.ThenStatus(WorkflowStatus.").Append(result.State.Status).Append(");\n    }\n");
        }

        private static void Sends(StringBuilder text, SimulationResult result)
        {
            string[] sent = result.Sent.Select(c => "\"" + c.Command + "\"").ToArray();
            text.Append("\n            .ThenSends(").Append(string.Join(", ", sent)).Append(");\n");
        }

        // The event the instance waits for now: the step's success, or the compensation's.
        private static string? Awaited(WorkflowDefinition workflow, SimulationState state)
        {
            WorkflowStep? step = state.Step is null ? null : workflow.Step(state.Step);
            return state.Status == WorkflowStatus.Compensating ? step?.Compensate?.Await?.Success.On : step?.Await?.Success.On;
        }

        private static IEnumerable<string> Captures(WorkflowDefinition workflow, SimulationState state)
        {
            if (state.Status == WorkflowStatus.Running && state.Step is not null && workflow.Step(state.Step)?.Await?.Success is { } success)
            {
                return success.Capture.Select(c => c.Path.Substring("event.data.".Length).Split('.')[0]);
            }

            return Array.Empty<string>();
        }

        // Finds start values for the data fields the path's guards read, so the real guards take the path's decisions.
        private static bool SolveGuards(WorkflowDefinition workflow, WorkflowPath path, Dictionary<string, object?> startData, ManifestMessage? start)
        {
            if (path.Guards.Count == 0)
            {
                return true;
            }

            var guards = new List<(GuardExpr Expression, bool Decision)>();
            var variables = new SortedDictionary<string, List<object?>>(StringComparer.Ordinal);
            foreach (KeyValuePair<string, bool> decision in path.Guards)
            {
                if (workflow.Step(decision.Key)?.When is not { } when || GuardParser.Parse(when).Expression is not { } expression)
                {
                    return false;
                }

                guards.Add((expression, decision.Value));
                foreach ((string dataField, List<object?> candidates) in Variables(expression))
                {
                    if (workflow.Data.FirstOrDefault(d => d.Name == dataField)?.From is not { } from)
                    {
                        return false;   // only start-sourced data can be chosen
                    }

                    string field = from.Substring("start.data.".Length);
                    if (!variables.TryGetValue(field, out List<object?>? all))
                    {
                        variables[field] = all = new List<object?> { startData.TryGetValue(field, out object? current) ? current : null };
                    }

                    all.AddRange(candidates.Where(c => !all.Contains(c)));
                }
            }

            string[] names = variables.Keys.ToArray();
            int combinations = names.Aggregate(1, (n, name) => n * Math.Max(1, variables[name].Count));
            for (int index = 0; index < Math.Min(combinations, 4096); index++)
            {
                var data = new Dictionary<string, object?>(startData, StringComparer.Ordinal);
                int rest = index;
                foreach (string name in names)
                {
                    List<object?> candidates = variables[name];
                    data[name] = candidates[rest % candidates.Count];
                    rest /= candidates.Count;
                }

                if (guards.All(g => GuardEvaluator.Evaluate(g.Expression, p => Value(workflow, data, p)) == g.Decision))
                {
                    foreach (string name in names)
                    {
                        startData[name] = data[name];
                    }

                    return true;
                }
            }

            return false;
        }

        private static object? Value(WorkflowDefinition workflow, Dictionary<string, object?> startData, string path)
        {
            if (!path.StartsWith("$data.", StringComparison.Ordinal) || workflow.Data.FirstOrDefault(d => d.Name == path.Substring(6))?.From is not { } from)
            {
                return null;
            }

            return startData.TryGetValue(from.Substring("start.data.".Length), out object? value) ? value : null;
        }

        // The $data fields a guard reads, with candidate values from its literals.
        private static IEnumerable<(string Field, List<object?> Candidates)> Variables(GuardExpr expression)
        {
            var literals = new List<object?>();
            var fields = new List<string>();
            Walk(expression, literals, fields);
            var candidates = new List<object?> { null, true, false, string.Empty, 0m };
            foreach (object? literal in literals)
            {
                candidates.Add(literal);
                if (literal is decimal number)
                {
                    candidates.Add(number + 1);
                    candidates.Add(number - 1);
                }
            }

            return fields.Distinct().Select(f => (f, candidates.Distinct().ToList()));
        }

        private static void Walk(GuardExpr expression, List<object?> literals, List<string> fields)
        {
            switch (expression)
            {
                case GuardLiteral literal:
                    literals.Add(literal.Value);
                    break;
                case GuardPath path when path.Path.StartsWith("$data.", StringComparison.Ordinal):
                    fields.Add(path.Path.Substring(6));
                    break;
                case GuardExists exists:
                    Walk(exists.Path, literals, fields);
                    break;
                case GuardUnary unary:
                    Walk(unary.Operand, literals, fields);
                    break;
                case GuardBinary binary:
                    Walk(binary.Left, literals, fields);
                    Walk(binary.Right, literals, fields);
                    break;
                case GuardIn @in:
                    Walk(@in.Value, literals, fields);
                    foreach (GuardExpr item in @in.Items)
                    {
                        Walk(item, literals, fields);
                    }

                    break;
            }
        }

        /// <summary>PascalCase from kebab-case: <c>order-fulfilment</c> → <c>OrderFulfilment</c>.</summary>
        public static string Pascal(string name)
        {
            var text = new StringBuilder();
            bool upper = true;
            foreach (char c in name ?? string.Empty)
            {
                if (!char.IsLetterOrDigit(c))
                {
                    upper = true;
                    continue;
                }

                text.Append(upper ? char.ToUpperInvariant(c) : c);
                upper = false;
            }

            return text.ToString();
        }

        private static string Xml(string text)
        {
            return text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
        }

        /// <summary>A raw C# string literal holding compact JSON.</summary>
        internal static string Json(IReadOnlyDictionary<string, object?> data)
        {
            var json = new StringBuilder("{");
            bool first = true;
            foreach (KeyValuePair<string, object?> pair in data)
            {
                if (!first)
                {
                    json.Append(',');
                }

                first = false;
                json.Append('"').Append(pair.Key).Append("\":");
                JsonValue(json, pair.Value);
            }

            return "\"\"\"" + json.Append('}') + "\"\"\"";
        }

        private static void JsonValue(StringBuilder json, object? value)
        {
            switch (value)
            {
                case null:
                    json.Append("null");
                    break;
                case bool b:
                    json.Append(b ? "true" : "false");
                    break;
                case decimal d:
                    json.Append(d.ToString(CultureInfo.InvariantCulture));
                    break;
                case string s:
                    json.Append('"').Append(s.Replace("\\", "\\\\").Replace("\"", "\\\"")).Append('"');
                    break;
                case IReadOnlyDictionary<string, object?> map:
                    json.Append('{');
                    bool first = true;
                    foreach (KeyValuePair<string, object?> pair in map)
                    {
                        if (!first)
                        {
                            json.Append(',');
                        }

                        first = false;
                        json.Append('"').Append(pair.Key).Append("\":");
                        JsonValue(json, pair.Value);
                    }

                    json.Append('}');
                    break;
                case IEnumerable<object?> list:
                    json.Append('[').Append(string.Join(",", list.Select(i =>
                    {
                        var item = new StringBuilder();
                        JsonValue(item, i);
                        return item.ToString();
                    }))).Append(']');
                    break;
                default:
                    json.Append('"').Append(Convert.ToString(value, CultureInfo.InvariantCulture)).Append('"');
                    break;
            }
        }

        // Deterministic sample values by field type; the correlation key carries the instance id.
        private sealed class Samples
        {
            private readonly string _correlationField;
            private int _counter;

            public Samples(WorkflowDefinition workflow)
            {
                int dot = workflow.Start.Correlate.LastIndexOf('.');
                _correlationField = dot >= 0 ? workflow.Start.Correlate.Substring(dot + 1) : workflow.Start.Correlate;
            }

            public Dictionary<string, object?> Message(ManifestMessage? message, string? correlationValue, IEnumerable<string>? distinct = null)
            {
                var data = new Dictionary<string, object?>(StringComparer.Ordinal);
                if (message is null)
                {
                    if (correlationValue is not null)
                    {
                        data[_correlationField] = correlationValue;
                    }

                    return data;
                }

                var unique = new HashSet<string>(distinct ?? Array.Empty<string>(), StringComparer.Ordinal);
                foreach (ManifestField field in message.Fields)
                {
                    if (field.Name == _correlationField)
                    {
                        data[field.Name] = correlationValue ?? Sample(field, "instance");
                    }
                    else
                    {
                        data[field.Name] = Sample(field, unique.Contains(field.Name) ? "captured-" + (++_counter).ToString(CultureInfo.InvariantCulture) : field.Name);
                    }
                }

                return data;
            }

            private static object? Sample(ManifestField field, string seed)
            {
                switch (field.Type)
                {
                    case "uuid": return WorkflowIds.Version5(WorkflowIds.Namespace, "sample/" + seed).ToString("D");
                    case "integer": return 1m;
                    case "number": return 100m;
                    case "boolean": return false;
                    case "date-time": return "2026-01-01T00:00:00Z";
                    case "date": return "2026-01-01";
                    case "time": return "12:00:00";
                    case "duration": return "PT1M";
                    case "uri": return "https://example.org/" + seed;
                    case "array": return new List<object?>();
                    case "object": return new Dictionary<string, object?>();
                    default: return "sample-" + seed;
                }
            }
        }
    }
