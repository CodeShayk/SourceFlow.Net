using System.Text;
using SourceFlow.Runtime;

namespace SourceFlow.Migration;

/// <summary>The code <c>migrate v2 scaffold</c> generates for one v2 table (doc 12 §3).</summary>
internal static class V2Scaffold
{
    public static string Generate(string namespaceName, string table, IReadOnlyList<V2Column> columns, AggregateDescriptor? aggregate)
    {
        string name = V2Migration.Identifier(table);
        string row = "V2" + name;
        string aggregateType = aggregate is null ? "TodoAggregate" : "global::" + aggregate.StateType.FullName!.Replace('+', '.');
        string idType = aggregate is null ? "TodoId" : "global::" + aggregate.IdType.FullName!.Replace('+', '.');
        var members = columns.Select(c => (Column: c, Property: Property(c.Name), Type: ClrType(c), Reader: Reader(c))).ToList();

        var code = new StringBuilder();
        code.AppendLine("// Generated by 'dotnet sourceflow migrate v2 scaffold' (doc 12 §3). Complete the TODOs, then keep this file with the service.");
        code.AppendLine("using System;");
        code.AppendLine("using System.Collections.Generic;");
        code.AppendLine("using SourceFlow;");
        code.AppendLine("using SourceFlow.Migration;");
        code.AppendLine();
        code.Append("namespace ").Append(namespaceName).AppendLine(";");
        code.AppendLine();
        if (aggregate is null)
        {
            code.Append("#warning No v3 aggregate is named like the v2 table '").Append(table).AppendLine("': replace TodoAggregate and TodoId.");
            code.AppendLine();
        }

        code.Append("/// <summary>A row of the v2 table <c>").Append(Escape(table)).AppendLine("</c>.</summary>");
        code.Append("public sealed record ").Append(row).Append('(');
        code.AppendJoin(", ", members.Select(m => m.Type + " " + m.Property));
        code.Append(") : IV2Entity<").Append(row).AppendLine(">");
        code.AppendLine("{");
        code.Append("    /// <inheritdoc/>").AppendLine();
        code.Append("    public static string TableName => \"").Append(Literal(table)).AppendLine("\";");
        code.AppendLine();
        code.Append("    /// <inheritdoc/>").AppendLine();
        code.Append("    public static ").Append(row).AppendLine(" Read(V2Row row)");
        code.AppendLine("    {");
        code.AppendLine("        return new(");
        for (int i = 0; i < members.Count; i++)
        {
            code.Append("            row.").Append(members[i].Reader).Append("(\"").Append(Literal(members[i].Column.Name)).Append("\")").AppendLine(i < members.Count - 1 ? "," : ");");
        }

        code.AppendLine("    }");
        code.AppendLine("}");
        code.AppendLine();
        code.Append("/// <summary>Imports v2 <c>").Append(Escape(table)).AppendLine("</c> rows as genesis events.</summary>");
        code.Append("public sealed class ").Append(name).Append("Import : IV2Import<").Append(row).Append(", ").Append(aggregateType).Append(", ").Append(idType).AppendLine(">");
        code.AppendLine("{");
        code.AppendLine("    /// <inheritdoc/>");
        code.Append("    public ").Append(idType).Append(" MapId(").Append(row).AppendLine(" entity)");
        code.AppendLine("    {");
        code.Append("        return V2Ids.FromLegacy<").Append(idType).AppendLine(">(entity.Id);");
        code.AppendLine("    }");
        code.AppendLine();
        code.AppendLine("    /// <inheritdoc/>");
        code.Append("    public IEnumerable<IEvent> ToEvents(").Append(row).AppendLine(" entity, V2ImportContext context)");
        code.AppendLine("    {");
        code.Append("        // TODO: the stream's genesis events, for example a ").Append(name).AppendLine("Imported event holding the current state");
        code.AppendLine("        // (and a When(…Imported) handler on the aggregate and its projections).");
        code.Append("        throw new NotImplementedException(\"Map v2 ").Append(Literal(table)).AppendLine(" rows to events.\");");
        code.AppendLine("    }");
        code.AppendLine();
        code.AppendLine("    /// <inheritdoc/>");
        code.Append("    public IEnumerable<string> Compare(").Append(row).Append(" entity, ").Append(aggregateType).AppendLine(" state)");
        code.AppendLine("    {");
        code.AppendLine("        // TODO: yield a description of each field whose v3 state differs from the v2 row, for 'migrate v2 verify'.");
        code.AppendLine("        yield break;");
        code.AppendLine("    }");
        code.AppendLine("}");
        return code.ToString();
    }

    private static string Property(string column)
    {
        return V2Migration.Identifier(column);
    }

    private static string ClrType(V2Column column)
    {
        return Kind(column.DataType) switch
        {
            "int" => "int",
            "long" => "long",
            "bool" => "bool",
            "decimal" => "decimal",
            "double" => "double",
            "datetime" => "DateTime",
            "bytes" => "byte[]?",
            _ => "string?",
        };
    }

    private static string Reader(V2Column column)
    {
        return Kind(column.DataType) switch
        {
            "int" => "Int32",
            "long" => "Int64",
            "bool" => "Boolean",
            "decimal" => "Decimal",
            "double" => "Double",
            "datetime" => "DateTime",
            "bytes" => "Bytes",
            _ => "String",
        };
    }

    // INFORMATION_SCHEMA data types on PostgreSQL and SQL Server, and the SQLite-style types v2's table helper wrote.
    private static string Kind(string dataType)
    {
        return dataType.ToUpperInvariant() switch
        {
            "INTEGER" or "INT" or "INT4" or "SMALLINT" or "INT2" or "TINYINT" => "int",
            "BIGINT" or "INT8" => "long",
            "BIT" or "BOOLEAN" or "BOOL" => "bool",
            "DECIMAL" or "NUMERIC" or "MONEY" or "SMALLMONEY" => "decimal",
            "REAL" or "FLOAT" or "DOUBLE PRECISION" or "FLOAT4" or "FLOAT8" => "double",
            "DATE" or "DATETIME" or "DATETIME2" or "SMALLDATETIME" or "DATETIMEOFFSET" or "TIMESTAMP" or "TIMESTAMP WITHOUT TIME ZONE" or "TIMESTAMP WITH TIME ZONE" => "datetime",
            "BYTEA" or "VARBINARY" or "BINARY" or "IMAGE" or "BLOB" => "bytes",
            _ => "string",
        };
    }

    private static string Literal(string value)
    {
        return value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal);
    }

    private static string Escape(string value)
    {
        return value.Replace("&", "&amp;", StringComparison.Ordinal).Replace("<", "&lt;", StringComparison.Ordinal).Replace(">", "&gt;", StringComparison.Ordinal);
    }
}
